    bool NetworkAliasesMatch,
    bool ConfigMountMatches,
    bool CommandMatches,
    bool StartupUserMatches,
    string ProtectedEvidenceAccess,
    bool ImageApproved,
    bool SecretPresent,
    bool ConfigPresent,
    bool ConfigHashMatches,
    bool SecurityPolicyApplied,
    bool RelayPortsPublished,
    bool DomainDriftDetected);


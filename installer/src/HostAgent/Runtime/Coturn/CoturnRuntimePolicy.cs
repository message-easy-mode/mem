public static class CoturnRuntimePolicy
{
    public const string ServiceKey = "coturn";
    public const string ContainerName = "mem-coturn";
    public const string ComponentLabel = "platform";
    public const string SecurityPolicyVersion = "mem-0.2.0-v2";
    public const string ContainerConfigPath = "/etc/coturn/turnserver.conf";
    public const string ExpectedRestartPolicy = "unless-stopped";
    public const string StartupUser = "0:0";
    public const int TurnPort = 3478;
    public const int RelayMinPort = 49160;
    public const int RelayMaxPort = 49200;
    public const int UserQuota = 12;
    public const int TotalQuota = 1200;

